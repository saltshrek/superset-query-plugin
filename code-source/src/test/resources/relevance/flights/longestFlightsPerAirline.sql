-- Each airline's longest scheduled route.

WITH routes AS (
  SELECT DISTINCT AIRLINE, ORIGIN_AIRPORT, DESTINATION_AIRPORT, DISTANCE
  FROM flights
)
SELECT AIRLINE, ORIGIN_AIRPORT, DESTINATION_AIRPORT, DISTANCE
FROM (
  SELECT
    *,
    ROW_NUMBER() OVER (PARTITION BY AIRLINE ORDER BY DISTANCE DESC) AS rnk
  FROM routes
)
WHERE rnk = 1
ORDER BY DISTANCE DESC;
